"""fft_longfir — learned LONG FIR filters realized as cheap FFT fast-convolutions,
sandwiched between time-domain mixed-activation nonlinearities (a Wiener-Hammerstein
cascade: pre-FIR -> waveshaper -> post-FIR -> waveshaper).

Why this can match a TCN's harmonic generation more cheaply
-----------------------------------------------------------
These circuits are (long linear filter) o (instantaneous nonlinearity) o (long linear
filter). A dilated TCN spends most of its parameters and FLOPs building the LONG linear
memory (the receptive field) out of stacked short kernels; the harmonics come from its
gated pointwise nonlinearity. Here we make the long-memory part EXPLICIT and CHEAP: a
single learned FIR of length ``L`` (512-2048) is one parameter vector per channel and is
applied as ``irfft(rfft(x) * rfft(kernel))`` — O(T log T) instead of O(T*L). A length-1024
FIR (~23 ms at 44.1 kHz) already exceeds the default TCN receptive field (1021 samples)
but costs ``L`` params per channel rather than a whole dilated stack.

The harmonics are generated by genuine TIME-DOMAIN pointwise nonlinearities (the
``_MixedActivation`` group: tanh/gelu/relu/abs/snake) placed BETWEEN the FIR stages, so a
small channel count can both (a) shape the transfer curve and (b) carry the pre/post
linear coloration that a pure spectral mask could never create on its own.

Realization & arbitrary length
-------------------------------
For length-``T`` input we zero-pad input and kernel to ``n = next_pow2(T + L - 1)``,
multiply in the rFFT domain, irfft, and crop ``[:T]``. Padding to ``T + L - 1`` makes this
a genuine LINEAR (not circular) convolution; cropping the causal head ``[:T]`` keeps the
filter strictly causal (kernel taps index into the past), so an overlap-save streaming
build is feasible with latency ~= one FFT block (not the FIR length — overlap-save hides
it). Per-channel learnable input gain + bias feed the waveshaper so it sees a properly
ranged signal regardless of the (already input-scaled) drive.
"""

from __future__ import annotations

import torch
from torch import nn

from vguitar.models.tcn import _MixedActivation

APPROACH = (
    "Learned long FIRs (L~1024) via rFFT fast-conv as cheap linear mixing, sandwiched "
    "between time-domain mixed-activation waveshapers (Wiener-Hammerstein cascade)."
)
COST = (
    "~30-70k params at channels=24 (dominated by 2 FIR banks of L*channels taps). "
    "Per-sample FLOPs O(stages*channels*log T) from FFTs + O(channels^2) pointwise mix; "
    "no per-sample dilated stack. Causal (kernels index the past, output cropped to head) "
    "-> streamable via overlap-save with latency ~= one FFT hop (not L); offline screen "
    "uses one full-length FFT per call."
)


def _next_pow2(n: int) -> int:
    """Smallest power of two >= n (FFT-friendly transform length)."""
    return 1 << (max(1, n - 1)).bit_length()


class _FFTLongFIR(nn.Module):
    """A bank of ``channels`` independent length-``L`` learned FIRs via rFFT fast-conv.

    Applied per channel: ``y[c] = irfft(rfft(x[c]) * rfft(kernel[c]))[:T]``. The kernel is
    initialised to a near-identity (unit tap at lag 0, tiny noise elsewhere) so the stack
    starts as an approximate pass-through and gradients flow into the long tail.
    """

    def __init__(self, channels: int, length: int) -> None:
        super().__init__()
        self.length = length
        k = torch.zeros(channels, length)
        k[:, 0] = 1.0
        k = k + 0.01 * torch.randn(channels, length)
        self.kernel = nn.Parameter(k)

    def forward(self, x: torch.Tensor) -> torch.Tensor:  # (B, C, T) -> (B, C, T)
        t = x.shape[-1]
        n = _next_pow2(t + self.length - 1)
        x_f = torch.fft.rfft(x, n=n, dim=-1)
        k_f = torch.fft.rfft(self.kernel, n=n, dim=-1).unsqueeze(0)  # (1, C, n//2+1)
        y = torch.fft.irfft(x_f * k_f, n=n, dim=-1)
        return y[..., :t]


class Net(nn.Module):
    """Wiener-Hammerstein cascade: pre-FIR -> mixed nonlinearity -> post-FIR -> nonlinearity.

    Lift to ``channels``, run two learned-long-FIR linear-mixing stages each followed by a
    heterogeneous time-domain nonlinearity (the harmonic generators), with a ``1x1`` channel
    mix after each FIR so the per-channel filters can recombine, then project to one channel.
    """

    out_bound: torch.Tensor

    def __init__(self, channels: int = 24, fir_len: int = 1024) -> None:
        super().__init__()
        self.fir_len = fir_len
        # lift 1 -> channels (pointwise, cheap)
        self.lift = nn.Conv1d(1, channels, 1)

        # stage 1: long FIR (linear memory) -> channel mix -> waveshaper (harmonics)
        self.fir1 = _FFTLongFIR(channels, fir_len)
        self.mix1 = nn.Conv1d(channels, channels, 1)
        self.act1 = _MixedActivation(channels)

        # stage 2: long FIR -> channel mix -> waveshaper
        self.fir2 = _FFTLongFIR(channels, fir_len)
        self.mix2 = nn.Conv1d(channels, channels, 1)
        self.act2 = _MixedActivation(channels)

        # output head: pointwise nonlinear mix -> single channel
        self.head = nn.Sequential(
            nn.Conv1d(channels, channels, 1),
            nn.GELU(),
            nn.Conv1d(channels, 1, 1),
        )
        self.register_buffer("out_bound", torch.tensor(1.0))

    def forward(self, x: torch.Tensor, c_sys: torch.Tensor | None = None) -> torch.Tensor:
        del c_sys  # single-circuit screen: always None, ignored
        h = self.lift(x.unsqueeze(1))  # (B, C, T)
        h = self.act1(self.mix1(self.fir1(h)))
        h = self.act2(self.mix2(self.fir2(h)))
        return self.head(h).squeeze(1)  # (B, T)


if __name__ == "__main__":
    for T in (2048, 4096, 1000):  # must handle arbitrary lengths
        net = Net(channels=16)
        y = net(torch.randn(2, T))
        assert y.shape == (2, T) and torch.isfinite(y).all(), (T, tuple(y.shape))
    print("OK", sum(p.numel() for p in Net(channels=24).parameters()), "params")
